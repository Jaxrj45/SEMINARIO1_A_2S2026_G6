-- =====================================================
-- REINICIAR TABLAS (BORRAR DATOS)
-- Vacia las tablas y reinicia los contadores de ID,
-- conservando la estructura. Se puede ejecutar sola.
-- =====================================================

DO $$
BEGIN
    IF to_regclass('public.lista_reproduccion') IS NOT NULL
       AND to_regclass('public.pelicula') IS NOT NULL
       AND to_regclass('public.usuario') IS NOT NULL THEN
        TRUNCATE TABLE "lista_reproduccion", "pelicula", "usuario"
            RESTART IDENTITY CASCADE;
    END IF;
END $$;

-- =====================================================
-- CREAR TABLAS
