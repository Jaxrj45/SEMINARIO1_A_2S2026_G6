CREATE SCHEMA IF NOT EXISTS cloudcinema;

DROP VIEW IF EXISTS cloudcinema.v_mi_lista CASCADE;
DROP VIEW IF EXISTS cloudcinema.v_cartelera CASCADE;
DROP TABLE IF EXISTS cloudcinema.lista_reproduccion CASCADE;
DROP TABLE IF EXISTS cloudcinema.pelicula CASCADE;
DROP TABLE IF EXISTS cloudcinema.usuario CASCADE;
DROP TYPE IF EXISTS cloudcinema.estado_pelicula CASCADE;

CREATE TYPE cloudcinema.estado_pelicula AS ENUM (
  'DISPONIBLE',
  'PROXIMO_ESTRENO'
);

CREATE TABLE cloudcinema.usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nombre_completo VARCHAR(120) NOT NULL,
  correo VARCHAR(150) NOT NULL,
  password_md5 CHAR(32) NOT NULL,
  foto_perfil VARCHAR(255),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT (NOW()),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT (NOW()),
  CONSTRAINT ck_usuario_correo CHECK (correo ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
  CONSTRAINT ck_usuario_password CHECK (password_md5 ~ '^[a-f0-9]{32}$'),
  CONSTRAINT ck_usuario_foto CHECK (foto_perfil IS NULL OR foto_perfil LIKE 'Fotos_Perfil/%'),
  CONSTRAINT ck_usuario_nombre CHECK (LENGTH(TRIM(nombre_completo)) > 0),
  PRIMARY KEY (id_usuario)
);

CREATE TABLE cloudcinema.pelicula (
  id_pelicula BIGINT GENERATED BY DEFAULT AS IDENTITY,
  titulo VARCHAR(200) NOT NULL,
  director VARCHAR(150) NOT NULL,
  anio_estreno SMALLINT NOT NULL,
  url_contenido VARCHAR(500) NOT NULL,
  poster VARCHAR(255) NOT NULL,
  estado cloudcinema.estado_pelicula NOT NULL DEFAULT 'DISPONIBLE',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT (NOW()),
  CONSTRAINT ck_pelicula_anio CHECK (anio_estreno BETWEEN 1888 AND 2100),
  CONSTRAINT ck_pelicula_url CHECK (url_contenido ~* '^https?://'),
  CONSTRAINT ck_pelicula_poster CHECK (poster LIKE 'Fotos_Peliculas/%'),
  PRIMARY KEY (id_pelicula)
);

CREATE TABLE cloudcinema.lista_reproduccion (
  id_lista BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_usuario BIGINT NOT NULL,
  id_pelicula BIGINT NOT NULL,
  agregada_en TIMESTAMPTZ NOT NULL DEFAULT (NOW()),
  PRIMARY KEY (id_lista)
);

CREATE UNIQUE INDEX uq_usuario_correo ON cloudcinema.usuario (correo);
CREATE INDEX idx_usuario_correo_lower ON cloudcinema.usuario ((LOWER(correo)));
CREATE UNIQUE INDEX uq_pelicula_obra ON cloudcinema.pelicula (titulo, director, anio_estreno);
CREATE INDEX idx_pelicula_estado ON cloudcinema.pelicula (estado);
CREATE UNIQUE INDEX uq_lista_usuario_pel ON cloudcinema.lista_reproduccion (id_usuario, id_pelicula);
CREATE INDEX idx_lista_usuario_fecha ON cloudcinema.lista_reproduccion (id_usuario, agregada_en DESC);
CREATE INDEX idx_lista_pelicula ON cloudcinema.lista_reproduccion (id_pelicula);

ALTER TABLE cloudcinema.lista_reproduccion
  ADD CONSTRAINT fk_lista_usuario FOREIGN KEY (id_usuario)
  REFERENCES cloudcinema.usuario (id_usuario)
  ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE cloudcinema.lista_reproduccion
  ADD CONSTRAINT fk_lista_pelicula FOREIGN KEY (id_pelicula)
  REFERENCES cloudcinema.pelicula (id_pelicula)
  ON DELETE CASCADE ON UPDATE CASCADE;

CREATE OR REPLACE FUNCTION cloudcinema.fn_usuario_touch()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizado_en := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER tg_usuario_touch
  BEFORE UPDATE ON cloudcinema.usuario
  FOR EACH ROW EXECUTE FUNCTION cloudcinema.fn_usuario_touch();

CREATE OR REPLACE FUNCTION cloudcinema.fn_lista_solo_disponibles()
RETURNS TRIGGER AS $$
DECLARE
    v_estado cloudcinema.estado_pelicula;
BEGIN
    SELECT estado INTO v_estado FROM cloudcinema.pelicula WHERE id_pelicula = NEW.id_pelicula;
    IF v_estado <> 'DISPONIBLE' THEN
        RAISE EXCEPTION 'La pelicula % es un proximo estreno y no puede agregarse a la lista.', NEW.id_pelicula
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER tg_lista_solo_disponibles
  BEFORE INSERT ON cloudcinema.lista_reproduccion
  FOR EACH ROW EXECUTE FUNCTION cloudcinema.fn_lista_solo_disponibles();

CREATE OR REPLACE VIEW cloudcinema.v_cartelera AS
SELECT p.id_pelicula,
       p.titulo,
       p.director,
       p.anio_estreno,
       p.url_contenido,
       p.poster,
       p.estado,
       (p.estado = 'DISPONIBLE') AS se_puede_agregar
FROM cloudcinema.pelicula p;

CREATE OR REPLACE VIEW cloudcinema.v_mi_lista AS
SELECT l.id_lista,
       l.id_usuario,
       p.id_pelicula,
       p.titulo,
       p.director,
       p.anio_estreno,
       p.url_contenido,
       p.poster,
       l.agregada_en
FROM cloudcinema.lista_reproduccion l
JOIN cloudcinema.pelicula p ON p.id_pelicula = l.id_pelicula;
