-- =====================================================
-- TRIGGERS DE FECHAS
-- creado_en / agregada_en se fijan al insertar y ya no
-- se pueden modificar. actualizado_en se refresca solo
-- en cada UPDATE.
-- =====================================================

CREATE OR REPLACE FUNCTION "fn_usuario_timestamps"()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.creado_en := NOW();
        NEW.actualizado_en := NOW();
    ELSE
        NEW.creado_en := OLD.creado_en;
        NEW.actualizado_en := NOW();
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER "tg_usuario_timestamps"
  BEFORE INSERT OR UPDATE ON "usuario"
  FOR EACH ROW EXECUTE FUNCTION "fn_usuario_timestamps"();

CREATE OR REPLACE FUNCTION "fn_pelicula_timestamps"()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.creado_en := NOW();
    ELSE
        NEW.creado_en := OLD.creado_en;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER "tg_pelicula_timestamps"
  BEFORE INSERT OR UPDATE ON "pelicula"
  FOR EACH ROW EXECUTE FUNCTION "fn_pelicula_timestamps"();

CREATE OR REPLACE FUNCTION "fn_lista_timestamps"()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.agregada_en := NOW();
    ELSE
        NEW.agregada_en := OLD.agregada_en;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER "tg_lista_timestamps"
  BEFORE INSERT OR UPDATE ON "lista_reproduccion"
  FOR EACH ROW EXECUTE FUNCTION "fn_lista_timestamps"();
